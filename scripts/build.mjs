/**
 * Build the browser bundle for dsh-fa-rtl.
 *
 * The shell loads `client.js` as a plain script that registers a factory with
 * `window.__ModuleLoader__`; there is no bundler in this package's pipeline and
 * no asset route to serve fonts from, so the woff2 files are embedded as data
 * URLs and the stylesheet is inlined into the factory.
 *
 * Run: node scripts/build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

/** One @font-face rule with the woff2 payload embedded. */
function fontFace(weight, file) {
  const data = readFileSync(join(root, 'fonts', file)).toString('base64')
  return [
    '@font-face{',
    'font-family:Vazirmatn;',
    'font-style:normal;',
    `font-weight:${weight};`,
    'font-display:swap;',
    `src:url(data:font/woff2;base64,${data}) format("woff2")`,
    '}'
  ].join('')
}

const fonts = [
  fontFace(400, 'Vazirmatn-Regular.woff2'),
  fontFace(500, 'Vazirmatn-Medium.woff2'),
  fontFace(700, 'Vazirmatn-Bold.woff2')
].join('\n')

const css = readFileSync(join(root, 'src', 'client.css'), 'utf8')
  .replace('/* @FONTS@ */', fonts)

const bundle = `/**
 * dsh-fa-rtl — browser half. GENERATED by scripts/build.mjs; edit src/client.css.
 *
 * Injects one stylesheet into the shell: the Vazirmatn @font-face set plus the
 * left-to-right guard for code. Reading direction is applied per prose block as
 * \`dir="auto"\`, so each paragraph resolves from its own first strong character
 * and no container's layout is mirrored. Code keeps its left-to-right direction.
 */
window.__ModuleLoader__.load({
  id: 'dsh-fa-rtl',
  factory: () => {
    const module = { exports: {} }

    const CSS = ${JSON.stringify(css)}

    const TAG_ID = 'dsh-fa-rtl'

    /** Leaf blocks that hold prose; a container is never given a direction. */
    const PROSE = 'p,ul,ol,li,h1,h2,h3,h4,h5,h6,blockquote,dt,dd,td,th,figcaption'
    /** Text buffers that are not prose blocks: composer and raw context panes. */
    const HOSTS = '[data-composer-input],[data-context-text],' +
      '[data-context-summary],[data-system-prompt-body]'

    /** \`dir="auto"\` once per element; the browser re-resolves on new text. */
    const mark = (el) => {
      if (el.hasAttribute('dir') === false) el.setAttribute('dir', 'auto')
    }

    const scan = (root) => {
      if (root.nodeType !== 1) return
      if (root.matches(HOSTS)) mark(root)
      if (root.matches(PROSE)) mark(root)
      for (const el of root.querySelectorAll(PROSE)) mark(el)
      for (const el of root.querySelectorAll(HOSTS)) mark(el)
    }

    /** Install the stylesheet and mark everything already on screen. */
    const install = () => {
      if (typeof document === 'undefined') return
      const root = document.documentElement
      if (root.getAttribute('lang') !== 'fa') root.setAttribute('lang', 'fa')
      const selector = 'style[data-plugin-css="' + TAG_ID + '"]'
      if (document.querySelector(selector) === null) {
        const tag = document.createElement('style')
        tag.dataset.plugin = 'dsh-fa-rtl'
        tag.dataset.pluginCss = TAG_ID
        tag.textContent = CSS
        document.head.appendChild(tag)
      }
      scan(document.body)
      /* Streamed answers arrive as new nodes; mark only what was added. */
      new MutationObserver((records) => {
        for (const record of records) for (const node of record.addedNodes) scan(node)
      }).observe(document.body, { childList: true, subtree: true })
    }

    if (document.readyState === 'loading') addEventListener('DOMContentLoaded', install, { once: true })
    else install()

    /** The stylesheet and the markers are the whole contribution. */
    function apply() {}

    module.exports = { apply, inject: [] }
    return module.exports
  }
})
`

writeFileSync(join(root, 'client.js'), bundle)
console.log('client.js', Buffer.byteLength(bundle), 'bytes')
